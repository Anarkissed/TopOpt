#!/usr/bin/env python3
"""Write core/src/fea/sheet_width_law_tables.inc from the CSVs (never typed by hand).

usage: python3 -I gen_tables.py <this folder> <out .inc>
  strength: <type>/kenv_widths.csv, the K*_law columns: the OFF-GRIP ENVELOPE over the 11-26 cut sweep
            (the reviewer's ruling of 2026-11-26, item 3 (a)), made to rise as N falls, never under
            today's law; one row per (N, rho)
  bending:  ../2026-11-25-sheet-laws-thin-members/bend/<type>_vf*_vpc24_nc2-...-8/<type>_bend.csv (unchanged)
  floor:    steady_env.csv's verdict (2 when every criterion passes for the type, else 3)
  passes:   kenv_checks.csv (1 when every check of the envelope law passes for the type)
"""
import csv
import glob
import os
import sys

ev, out = os.path.abspath(sys.argv[1]), sys.argv[2]
OLD = os.path.join(os.path.dirname(ev), "2026-11-25-sheet-laws-thin-members")
TYPES = [("gyroid", "Gyroid"), ("schwarz_d", "SchwarzD")]


def rows(p):
    with open(p) as f:
        return list(csv.DictReader(f))


def all_pass(path):
    v = {}
    for r in rows(path):
        v.setdefault(r["type"], True)
        v[r["type"]] = v[r["type"]] and r["pass"] == "1"
    return v


steady = all_pass(os.path.join(ev, "steady_env.csv"))
passes = all_pass(os.path.join(ev, "kenv_checks.csv"))

L = ["// GENERATED by evidence/2026-11-26-sheet-laws-envelope/gen_tables.py from the CSVs.",
     "// Do not edit: re-run the generator (that folder's reproduce.sh does). test_sheet_width_law pins every row.",
     "// Inside sheet_width_law.cpp's anonymous namespace (WidthLawRow, BendRow)."]
for t, T in TYPES:
    kf = rows(os.path.join(ev, t, "kenv_widths.csv"))
    kf.sort(key=lambda r: (int(r["N"]), float(r["rho_lib"])))
    L.append("")
    L.append(f"// {t}: strength per width, the K*_law columns of {t}/kenv_widths.csv (the off-grip envelope over")
    L.append("// the cut sweep, the monotone rule, never under today's law); each row's pitch, wall in voxels, and")
    L.append("// where its Kd comes from.")
    L.append(f"constexpr WidthLawRow k{T}WidthLaw[] = {{")
    for r in kf:
        L.append("    {%d, %.5f, %.4f, %.4f, %.4f, %.4f},  // vpc %s, wall %s vox (true %s); %s" % (
            int(r["N"]), float(r["rho_lib"]), float(r["Kd_law"]), float(r["Kv_law"]),
            float(r["Kild_law"]), float(r["Kilv_law"]),
            r["vpc_min"] if r["vpc_min"] == r["vpc_max"] else r["vpc_min"] + "-" + r["vpc_max"],
            r["wall_vox_min"], r["wall_true_vox_min"], r["law_from"]))
    L.append("};")
    pts = []
    for d in sorted(glob.glob(os.path.join(OLD, "bend", f"{t}_vf*_vpc24_nc2-3-4-5-6-7-8"))):
        for r in rows(os.path.join(d, f"{t}_bend.csv")):
            pts.append((int(r["cells_across"]), float(r["cell_rho"]), float(r["bend_err_pct"]) / 100.0,
                        os.path.basename(d)))
    pts.sort()
    L.append(f"// {t}: bending error (fraction; + = the averaged member too stiff),")
    L.append(f"// ../2026-11-25-sheet-laws-thin-members/bend/*_vpc24_*/{t}_bend.csv")
    L.append(f"constexpr BendRow k{T}Bend[] = {{")
    for n, rho, e, d in pts:
        L.append("    {%d, %.4f, %.4f},  // %s" % (n, rho, e, d))
    L.append("};")
    fl = 2 if steady.get(t, False) else 3
    L.append(f"// {t}: the 2-cell rows {'came out steady' if fl == 2 else 'did not come out steady'} (steady_env.csv)")
    L.append(f"constexpr int k{T}Floor = {fl};")
    ok = passes.get(t, False)
    L.append(f"// {t}: the envelope law {'passes' if ok else 'does NOT pass'} every check of kenv_checks.csv")
    L.append(f"constexpr bool k{T}EnvelopeLawPasses = {'true' if ok else 'false'};")
with open(out, "w") as f:
    f.write("\n".join(L) + "\n")
print("wrote", out)
