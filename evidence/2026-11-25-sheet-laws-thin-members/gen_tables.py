#!/usr/bin/env python3
"""Write core/src/fea/sheet_width_law_tables.inc from this folder's CSVs (never typed by hand).

usage: python3 -I gen_tables.py <this folder> <out .inc>
  strength: <type>/kfit_widths.csv, the K*_law columns (11-09's populations at the law pitch, made to
            rise as N falls, never under today's law), one row per (N, rho)
  bending:  bend/<type>_vf*_vpc24_nc2-...-8/<type>_bend.csv, the error at 2..8 cells, three densities
  floor:    steady.csv's verdict (2 when every criterion passes for the type, else 3)
"""
import csv
import glob
import os
import sys

ev, out = sys.argv[1], sys.argv[2]
TYPES = [("gyroid", "Gyroid"), ("schwarz_d", "SchwarzD")]


def rows(p):
    with open(p) as f:
        return list(csv.DictReader(f))


steady = {}
for r in rows(os.path.join(ev, "steady.csv")):
    steady.setdefault(r["type"], True)
    steady[r["type"]] = steady[r["type"]] and r["pass"] == "1"

L = ["// GENERATED by evidence/2026-11-25-sheet-laws-thin-members/gen_tables.py from that folder's CSVs.",
     "// Do not edit: re-run the generator (reproduce.sh does). test_sheet_width_law pins every row.",
     "// Inside sheet_width_law.cpp's anonymous namespace (WidthLawRow, BendRow)."]
for t, T in TYPES:
    kf = rows(os.path.join(ev, t, "kfit_widths.csv"))
    kf.sort(key=lambda r: (int(r["N"]), float(r["rho_lib"])))
    L.append("")
    L.append(f"// {t}: strength per width, the K*_law columns of {t}/kfit_widths.csv; each row's pitch, its")
    L.append("// median wall run and true wall in voxels, and the fixture that sets its Kd before the envelope.")
    L.append(f"constexpr WidthLawRow k{T}WidthLaw[] = {{")
    for r in kf:
        L.append("    {%d, %.5f, %.4f, %.4f, %.4f, %.4f},  // vpc %s, wall %s vox (true %s); %s" % (
            int(r["N"]), float(r["rho_lib"]), float(r["Kd_law"]), float(r["Kv_law"]),
            float(r["Kild_law"]), float(r["Kilv_law"]),
            r["vpc_min"] if r["vpc_min"] == r["vpc_max"] else r["vpc_min"] + "-" + r["vpc_max"],
            r["wall_vox_min"], r["wall_true_vox_min"], r["argmax"]))
    L.append("};")
    pts = []
    for d in sorted(glob.glob(os.path.join(ev, "bend", f"{t}_vf*_vpc24_nc2-3-4-5-6-7-8"))):
        for r in rows(os.path.join(d, f"{t}_bend.csv")):
            pts.append((int(r["cells_across"]), float(r["cell_rho"]), float(r["bend_err_pct"]) / 100.0,
                        os.path.basename(d)))
    pts.sort()
    L.append(f"// {t}: bending error (fraction; + = the averaged member too stiff), bend/*_vpc24_*/{t}_bend.csv")
    L.append(f"constexpr BendRow k{T}Bend[] = {{")
    for n, rho, e, d in pts:
        L.append("    {%d, %.4f, %.4f},  // %s" % (n, rho, e, d))
    L.append("};")
    fl = 2 if steady.get(t, False) else 3
    L.append(f"// {t}: the 2-cell rows {'came out steady' if fl == 2 else 'did not come out steady'} (steady.csv)")
    L.append(f"constexpr int k{T}Floor = {fl};")
with open(out, "w") as f:
    f.write("\n".join(L) + "\n")
print("wrote", out)
