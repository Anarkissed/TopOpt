// ComputeLocation.swift — WHERE a run executes (handoff 097, LAN offload Tier 2).
//
// The iPad is always the default and always present. When a Mac on the LAN is
// running "TopOpt Worker", it advertises the Bonjour service `_topopt._tcp` with
// its core fingerprint in the TXT record; this model BROWSES for those (NWBrowser)
// and surfaces each by its Bonjour name — the user never types an IP. Selecting a
// worker resolves its host:port (NWConnection) and caches a RemoteRunnerConfig the
// run flow uses; selecting "iPad" (or nothing) leaves the run byte-identical to
// before. An advanced manual host:port is offered as a fallback only.
//
// The selection persists per device (UserDefaults). The skew check compares a
// worker's advertised fingerprint to the app's own CoreFingerprint (generated by
// build_core.sh) so the picker can WARN before a run — the RemoteRunner's /health
// guard is the hard stop, this is the friendly heads-up.

import Foundation
import Combine
import Network

/// One worker discovered on the LAN. Identity is its Bonjour service name (stable
/// for a given Mac), so it persists across the endpoint churn of Wi-Fi roaming.
public struct DiscoveredWorker: Identifiable, Equatable {
    public let id: String                 // Bonjour service name, e.g. "Mac mini"
    public var name: String { id }
    /// The core fingerprint from the TXT record (nil if the worker didn't advertise
    /// one). Compared to `CoreFingerprint.value` to flag version skew before a run.
    public let fingerprint: String?
    let endpoint: NWEndpoint              // resolved to host:port on selection
}

/// The chosen compute location, persisted per device.
public enum ComputeChoice: Equatable, Codable {
    case local
    case worker(name: String)
    case manual(host: String, port: Int)
}

@MainActor
public final class ComputeLocationModel: ObservableObject {
    /// Workers currently visible on the LAN, sorted by name.
    @Published public private(set) var workers: [DiscoveredWorker] = []
    /// The user's choice. Setting it persists + (re)resolves the remote config.
    @Published public private(set) var choice: ComputeChoice = .local
    /// The resolved config for a remote choice, or nil for local / not-yet-resolved.
    /// The run flow reads THIS: nil → on-device bridge runner (byte-identical).
    /// ★ notes25 (D9): once a Mac is resolved, its live `/health` is asked (WorkerHealth.swift).
    @Published public private(set) var activeRemote: RemoteRunnerConfig? {
        didSet { if activeRemote != nil { checkHealth() } }
    }
    /// ★ notes25 (D9, the "Runs on ⚠" his Mac never deserved): each Mac's engine fingerprint as its live `/health` last said
    /// it, by name. The Bonjour advertisement is written once, when the worker app starts, so after a release swaps only the
    /// Mac's engine it goes stale; this wins over it whenever it is known (`isSkewed`).
    @Published public private(set) var liveFingerprints: [String: String] = [:]
    /// True while a selected worker's endpoint is still resolving.
    @Published public private(set) var resolving = false

    private let defaults: UserDefaults
    private let defaultsKey = "topopt.computeLocation.v1"
    private var browser: NWBrowser?

    public init(defaults: UserDefaults = .standard) {
        self.defaults = defaults
        restore()
        watchHealth()   // ★ notes25 (D9): coming back to the app, and every run's own /health, ask again
    }

    // MARK: - Discovery

    /// Start browsing `_topopt._tcp`. Idempotent; safe to call on every appear.
    public func startBrowsing() {
        if let t = Self.hostedTestDiscovery {   // hosted tests: no network
            DispatchQueue.main.asyncAfter(deadline: .now() + t.delay) { [weak self] in
                guard let self, case let .worker(name) = self.choice, name == t.name, let cfg = t.config else { return }
                self.activeRemote = cfg
            }
            return
        }
        guard browser == nil else { return }
        let params = NWParameters()
        params.includePeerToPeer = true
        let b = NWBrowser(for: .bonjourWithTXTRecord(type: "_topopt._tcp", domain: nil),
                          using: params)
        b.browseResultsChangedHandler = { [weak self] results, _ in
            Task { @MainActor in self?.ingest(results) }
        }
        b.stateUpdateHandler = { [weak self] state in
            if case .failed = state { Task { @MainActor in self?.stopBrowsing() } }
        }
        browser = b
        b.start(queue: .main)
    }

    public func stopBrowsing() {
        browser?.cancel()
        browser = nil
    }

    private func ingest(_ results: Set<NWBrowser.Result>) {
        var found: [DiscoveredWorker] = []
        for r in results {
            guard case let .service(name, _, _, _) = r.endpoint else { continue }
            var fingerprint: String?
            if case let .bonjour(txt) = r.metadata { fingerprint = txt["fingerprint"] }
            found.append(DiscoveredWorker(id: name, fingerprint: fingerprint,
                                          endpoint: r.endpoint))
        }
        found.sort { $0.name.localizedCaseInsensitiveCompare($1.name) == .orderedAscending }
        workers = found
        // If the persisted worker (re)appeared and we haven't resolved it yet,
        // resolve now so tapping Run just works.
        if case let .worker(name) = choice, activeRemote == nil,
           workers.contains(where: { $0.id == name }) {
            select(.worker(name: name))
        }
    }

    /// True when a worker's core differs from this app's — a run would be refused.
    /// ★ notes25 (D9): the Mac's live `/health` decides once it has answered; the Bonjour value is only a first hint.
    public func isSkewed(_ w: DiscoveredWorker) -> Bool {
        guard let fp = liveFingerprints[w.id] ?? w.fingerprint else { return false }   // unknown → don't cry wolf
        return fp != CoreFingerprint.value
    }

    /// The plain-English skew message shown in the picker + a pointer to the fix.
    /// ★ notes25 (D9): it named "Update core…", which the worker app does not have. What is wrong and how to fix it, true.
    public func skewMessage(_ w: DiscoveredWorker) -> String {
        Self.skewMessage(name: w.name)
    }
    static func skewMessage(name: String) -> String {
        "\(name) runs a different version of the engine than this app. Install the matching TopOpt release on the Mac, "
        + "then try again."
    }

    /// Tests only: the Macs Bonjour would list (with their advertised fingerprints).
    func listForTests(_ found: [DiscoveredWorker]) { workers = found }

    // MARK: - ★ notes25 (D9): the Mac's live engine fingerprint

    private let healthObservers = WorkerHealth.Observers()

    /// Ask the chosen Mac's `/health` for its engine fingerprint now (it was resolved, the app came back to the front, or
    /// a run is about to go). Quiet when nothing is chosen or resolved; an unreachable Mac keeps what was known.
    public func checkHealth() {
        guard let cfg = activeRemote, let name = rememberedName else { return }
        Task { @MainActor [weak self] in
            guard let fp = await WorkerHealth.fingerprint(cfg) else { return }
            self?.heard(fp, host: cfg.host, port: cfg.port, name: name)
        }
    }

    /// A `/health` answered `fingerprint` for the Mac at host:port — recorded for the remembered Mac when that is where the
    /// chosen one lives (a run's own pre-job check says it too, WorkerHealth.heard).
    func heard(_ fingerprint: String, host: String, port: Int, name: String? = nil) {
        guard let n = name ?? rememberedName else { return }
        if let cfg = activeRemote, cfg.host != host || cfg.port != port { return }   // another Mac's answer
        if liveFingerprints[n] != fingerprint { liveFingerprints[n] = fingerprint }
    }

    private func watchHealth() {
        let c = NotificationCenter.default
        healthObservers.add(c.addObserver(forName: WorkerHealth.answered, object: nil, queue: .main) { [weak self] n in
            guard let i = n.userInfo, let fp = i["fingerprint"] as? String, let host = i["host"] as? String,
                  let port = i["port"] as? Int else { return }
            MainActor.assumeIsolated { self?.heard(fp, host: host, port: port) }
        })
        if let front = WorkerHealth.cameToFront {
            healthObservers.add(c.addObserver(forName: front, object: nil, queue: .main) { [weak self] _ in
                MainActor.assumeIsolated { self?.checkHealth() }
            })
        }
    }

    // MARK: - Selection

    public func select(_ choice: ComputeChoice) {
        self.choice = choice
        persist()
        activeRemote = nil
        switch choice {
        case .local:
            resolving = false
        case .manual(let host, let port):
            activeRemote = RemoteRunnerConfig(host: host, port: port,
                                              expectedFingerprint: CoreFingerprint.value)
            resolving = false
        case .worker(let name):
            guard let w = workers.first(where: { $0.id == name }) else { return }
            resolving = true
            resolve(w.endpoint) { [weak self] resolved in
                Task { @MainActor in
                    guard let self, case .worker(name) = self.choice else { return }
                    self.resolving = false
                    guard let (host, port) = resolved else { return }
                    self.activeRemote = RemoteRunnerConfig(
                        host: host, port: port, expectedFingerprint: CoreFingerprint.value)
                }
            }
        }
    }

    /// ★ B1 (note 4, approved design 2026-11-02): the REMEMBERED choice is a Mac (a worker or a manual address), found on
    /// the network yet or not. "Is a Mac chosen?" reads this; only the send needs `activeRemote` (its resolved address).
    /// It used to read `activeRemote`, which stays nil until discovery runs, and discovery started only when Settings
    /// opened, so a run said "must go to the Mac" while the Mac was chosen.
    public var wantsRemote: Bool { choice != .local }

    /// The remembered Mac's name, for "Finding Nadim's Mac mini…".
    public var rememberedName: String? {
        switch choice {
        case .local: return nil
        case .worker(let name): return name
        case .manual(let host, _): return host
        }
    }

    /// How long Optimize looks for the remembered Mac before it says it isn't answering.
    nonisolated(unsafe) public static var findSeconds: Double = 8

    /// Hosted tests only: stands in for Bonjour (discover + resolve). The remembered worker `name` resolves to `config` after
    /// `delay` seconds; nil `config` = never found. The app never sets it.
    nonisolated(unsafe) static var hostedTestDiscovery: (name: String, config: RemoteRunnerConfig?, delay: Double)?

    /// A short label for the current choice, for the bottom-bar pill.
    public var label: String {
        switch choice {
        case .local: return "iPad"
        case .worker(let name): return name
        case .manual(let host, _): return host
        }
    }

    /// The name of the machine a run dispatched NOW would land on, or nil for a
    /// local run (task 2026-08-03-variant-entry-gating-and-retention, bar AJ5). It
    /// is stamped onto the finished outcome so a result can always say which
    /// machine solved it — the fact the maintainer could not read off the screen
    /// when a refusal told him to "re-run it on a Mac worker".
    public var selectedWorkerName: String? {
        guard activeRemote != nil else { return nil }
        switch choice {
        case .local: return nil
        case .worker(let name): return name
        case .manual(let host, let port): return "\(host):\(port)"
        }
    }

    /// Resolve a Bonjour service endpoint to a concrete host:port for URLSession by
    /// opening a throwaway NWConnection and reading its resolved path. LAN-typical
    /// IPv4 works directly; an IPv6 link-local address keeps its %zone (URLSession
    /// on Apple platforms accepts it). Times out via the connection's own failure.
    nonisolated private func resolve(_ endpoint: NWEndpoint,
                                     completion: @escaping ((String, Int)?) -> Void) {
        let conn = NWConnection(to: endpoint, using: .tcp)
        var finished = false
        func finish(_ result: (String, Int)?) {
            if finished { return }; finished = true
            conn.cancel()
            completion(result)
        }
        conn.stateUpdateHandler = { state in
            switch state {
            case .ready:
                if case let .hostPort(host, port) = conn.currentPath?.remoteEndpoint {
                    finish((Self.hostString(host), Int(port.rawValue)))
                } else { finish(nil) }
            case .failed, .cancelled:
                finish(nil)
            default:
                break
            }
        }
        conn.start(queue: .global())
    }

    nonisolated private static func hostString(_ host: NWEndpoint.Host) -> String {
        switch host {
        case .ipv4(let a): return "\(a)".components(separatedBy: "%").first ?? "\(a)"
        case .ipv6(let a): return "\(a)"
        case .name(let n, _): return n
        @unknown default: return "\(host)"
        }
    }

    // MARK: - Persistence (per device)

    private func persist() {
        if let data = try? JSONEncoder().encode(choice) {
            defaults.set(data, forKey: defaultsKey)
        }
    }

    private func restore() {
        guard let data = defaults.data(forKey: defaultsKey),
              let saved = try? JSONDecoder().decode(ComputeChoice.self, from: data)
        else { return }
        choice = saved
        // A saved manual address resolves immediately; a saved worker resolves once
        // discovery re-finds it (see `ingest`). Local needs nothing.
        if case .manual = saved { select(saved) }
    }
}
